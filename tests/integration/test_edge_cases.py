class TestDuplicateCompanyDetection:
    """Tests for detecting duplicate companies across origins."""

    @pytest.mark.asyncio
    async def test_same_name_different_casing(self, duplicate_companies):
        """Companies with ALL CAPS, lowercase, and title case should be detected as duplicates."""
        companies = duplicate_companies
        assert len(companies) == 3

        # All should have similar canonical names
        canonicals = set()
        for c in companies:
            name = (c.get("name") or "").lower().replace(".", "").replace(" corporation", "corp")
            canonicals.add(name.strip())

        # After normalization, they should be very similar
        assert len(canonicals) <= 3  # At most 3 unique

    @pytest.mark.asyncio
    async def test_company_address_variations(self, duplicate_companies):
        """Same company, different address abbreviations should be detected."""
        companies = duplicate_companies
        addresses = []
        for c in companies:
            addr = c.get("street", "")
            # Normalize abbreviations
            addr = addr.replace("Street", "St").replace("St.", "St")
            addresses.append(addr)

        # At least some addresses should be similar
        assert addresses[0] == addresses[1] or addresses[1] == addresses[2]


